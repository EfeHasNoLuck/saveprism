//! Golden corpus test.
//!
//! Every file under `fixtures/samples/**` and `fixtures/synthetic/**` is detected, round-trip checked
//! and compared with `fixtures/expected/<root>/<relative path>.toml`.
//! Regenerate expectations with `SAVEPRISM_BLESS=1 cargo test -p saveprism-codecs --test golden`.
//! This test never writes into `fixtures/samples`.

use std::fs;
use std::path::{Path, PathBuf};

use saveprism_codecs::register_all;
use saveprism_core::detect::{DetectOptions, detect};
use saveprism_core::guard::{Verdict, check_round_trip};
use saveprism_core::{Limits, Registry};

const ROOTS: [&str; 2] = ["samples", "synthetic"];
const BLESS_HEADER: &str = "# generated by SAVEPRISM_BLESS=1, review before committing\n";
const BLESS_COMMAND: &str = "SAVEPRISM_BLESS=1 cargo test -p saveprism-codecs --test golden";

/// What the pipeline found for one file.
struct Observed {
    recipe: String,
    guard: &'static str,
}

fn fixtures_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../fixtures")
}

fn is_skipped(name: &str) -> bool {
    // `witcher3-bundle` holds content bundles for the Gwent card reader tests: game containers,
    // not save documents, so detection has no codec for them.
    name.starts_with('.') || name.starts_with("README") || name == "witcher3-bundle"
}

/// Lists all regular files below `root` without recursion (explicit stack), sorted.
fn collect_files(root: &Path) -> Vec<PathBuf> {
    let mut files = Vec::new();
    let mut stack = vec![root.to_path_buf()];
    while let Some(dir) = stack.pop() {
        let Ok(entries) = fs::read_dir(&dir) else {
            continue;
        };
        for entry in entries.flatten() {
            let name = entry.file_name().to_string_lossy().into_owned();
            if is_skipped(&name) {
                continue;
            }
            let path = entry.path();
            match entry.file_type() {
                Ok(t) if t.is_dir() => stack.push(path),
                Ok(t) if t.is_file() => files.push(path),
                _ => {}
            }
        }
    }
    files.sort();
    files
}

/// Relative path with forward slashes.
fn relative(path: &Path, base: &Path) -> String {
    let rel = path.strip_prefix(base).unwrap_or(path);
    rel.components()
        .map(|c| c.as_os_str().to_string_lossy().into_owned())
        .collect::<Vec<_>>()
        .join("/")
}

fn verdict_name(verdict: Verdict) -> &'static str {
    match verdict {
        Verdict::Exact => "exact",
        Verdict::Semantic => "semantic",
        Verdict::Different => "different",
    }
}

fn observe(bytes: &[u8], file_name: &str, reg: &Registry) -> Result<Observed, String> {
    let limits = Limits::default();
    let opts = DetectOptions {
        file_name: Some(file_name.to_string()),
        ..DetectOptions::default()
    };
    let detection =
        detect(bytes, reg, &limits, &opts).map_err(|e| format!("detect failed: {e:?}"))?;
    let recipe = &detection.best.recipe;
    let report = check_round_trip(bytes, recipe, reg, &limits)
        .map_err(|e| format!("round-trip failed: {e:?}"))?;
    Ok(Observed {
        recipe: recipe.kinds().join(" > "),
        guard: verdict_name(report.overall),
    })
}

/// Parses `key = "value"` lines; comments and blank lines are ignored.
fn parse_expected(text: &str) -> Result<(Option<String>, Option<String>), String> {
    let mut recipe = None;
    let mut guard = None;
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            return Err(format!("malformed line: {line}"));
        };
        let value = value.trim();
        let Some(value) = value.strip_prefix('"').and_then(|v| v.strip_suffix('"')) else {
            return Err(format!("value must be a quoted string: {line}"));
        };
        match key.trim() {
            "recipe" => recipe = Some(value.to_string()),
            "guard" => guard = Some(value.to_string()),
            other => return Err(format!("unknown key: {other}")),
        }
    }
    Ok((recipe, guard))
}

fn render_expected(observed: &Observed) -> String {
    format!(
        "{BLESS_HEADER}recipe = \"{}\"\nguard = \"{}\"\n",
        observed.recipe, observed.guard
    )
}

#[test]
fn golden_corpus() {
    let fixtures = fixtures_dir();
    let bless = std::env::var("SAVEPRISM_BLESS").is_ok_and(|v| !v.is_empty() && v != "0");
    let mut reg = Registry::default();
    register_all(&mut reg);

    let mut failures: Vec<String> = Vec::new();
    let mut total = 0usize;

    for root in ROOTS {
        let root_dir = fixtures.join(root);
        if !root_dir.is_dir() {
            continue;
        }
        for file in collect_files(&root_dir) {
            total += 1;
            let rel = relative(&file, &root_dir);
            let label = format!("{root}/{rel}");
            let expected_path = fixtures
                .join("expected")
                .join(root)
                .join(format!("{rel}.toml"));

            let bytes = match fs::read(&file) {
                Ok(b) => b,
                Err(e) => {
                    failures.push(format!("{label}: cannot read file: {e}"));
                    continue;
                }
            };
            let name = file
                .file_name()
                .map(|n| n.to_string_lossy().into_owned())
                .unwrap_or_default();
            let observed = match observe(&bytes, &name, &reg) {
                Ok(o) => o,
                Err(message) => {
                    failures.push(format!("{label}: {message}"));
                    continue;
                }
            };

            if bless {
                // Expectations live under fixtures/expected only, never under samples.
                if let Some(parent) = expected_path.parent()
                    && let Err(e) = fs::create_dir_all(parent)
                {
                    failures.push(format!("{label}: cannot create {}: {e}", parent.display()));
                    continue;
                }
                if let Err(e) = fs::write(&expected_path, render_expected(&observed)) {
                    failures.push(format!(
                        "{label}: cannot write {}: {e}",
                        expected_path.display()
                    ));
                }
                continue;
            }

            let text = match fs::read_to_string(&expected_path) {
                Ok(t) => t,
                Err(_) => {
                    failures.push(format!(
                        "{label}: no expectation file at {} (found recipe = \"{}\", guard = \"{}\")",
                        expected_path.display(),
                        observed.recipe,
                        observed.guard
                    ));
                    continue;
                }
            };
            match parse_expected(&text) {
                Err(message) => failures.push(format!(
                    "{label}: bad expectation file {}: {message}",
                    expected_path.display()
                )),
                Ok((recipe, guard)) => {
                    if recipe.as_deref() != Some(observed.recipe.as_str()) {
                        failures.push(format!(
                            "{label}: recipe mismatch in {}: expected {:?}, found \"{}\"",
                            expected_path.display(),
                            recipe,
                            observed.recipe
                        ));
                    }
                    if guard.as_deref() != Some(observed.guard) {
                        failures.push(format!(
                            "{label}: guard mismatch in {}: expected {:?}, found \"{}\"",
                            expected_path.display(),
                            guard,
                            observed.guard
                        ));
                    }
                }
            }
        }
    }

    println!("golden corpus: {total} files");
    if !failures.is_empty() {
        panic!(
            "golden corpus: {} problem(s):\n  {}\n\nTo (re)generate expectations, review them, then commit:\n  {BLESS_COMMAND}",
            failures.len(),
            failures.join("\n  ")
        );
    }
}
