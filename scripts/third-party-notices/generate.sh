#!/usr/bin/env bash
# Regenerates THIRD_PARTY_NOTICES.md at the repo root.
# Needs: cargo-about (`cargo install cargo-about --locked`), pnpm, node. Run from anywhere: bash scripts/third-party-notices/generate.sh
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"
app="$root/apps/desktop"
web_out="$root/target/notices-web"
out="$root/THIRD_PARTY_NOTICES.md"

# Frontend build with source maps, only to learn which packages end up in the bundle.
pnpm -C "$app" exec vite build --sourcemap --outDir "$web_out" --emptyOutDir --logLevel warn

{
  echo "# Third-party notices"
  echo
  echo "SavePrism is MIT-licensed (see LICENSE). The Windows app includes the third-party software listed below,"
  echo "each under its own license. This file is generated by \`scripts/third-party-notices/generate.sh\`."
  echo
  cargo about generate --manifest-path "$root/apps/desktop/src-tauri/Cargo.toml" \
    -c "$here/about.toml" "$here/about.hbs"
  echo
  node "$here/npm.mjs" "$web_out" "$app"
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $out"
